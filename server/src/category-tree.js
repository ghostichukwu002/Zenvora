const byId = new Map();
for (const department of departments) {
  byId.set(department.id, { department });
  for (const category of department.categories) {
    byId.set(category.id, { department, category });
    for (const subcategory of category.subcategories) {
      byId.set(subcategory.id, { department, category, subcategory });
    }
  }
}

// Returns null when the placement is valid, or { code, message } describing the problem.
// A category that has subcategories needs one; a leaf category must not get one.
export function placementIssue({ departmentId, categoryId, subcategoryId }) {
  const department = byId.get(departmentId)?.department;
  if (!department) return { code: 'department_invalid', message: 'Choose a department from the list.' };
  const category = byId.get(categoryId)?.category;
  if (!category || !department.categories.some((c) => c.id === categoryId)) {
    return { code: 'category_invalid', message: 'That category does not belong to the chosen department.' };
  }
  const hasSubs = category.subcategories.length > 0;
  if (!subcategoryId) {
    return hasSubs ? { code: 'subcategory_required', message: 'Choose a subcategory for this category.' } : null;
  }
  if (!hasSubs || !category.subcategories.some((s) => s.id === subcategoryId)) {
    return { code: 'subcategory_invalid', message: 'That subcategory does not belong to the chosen category.' };
  }
  return null;
}

export function placementLabel(placement) {
  const hit = placement && byId.get(placement.subcategoryId ?? placement.categoryId);
  if (!hit) return null;
  return [hit.department.name, hit.category.name, hit.subcategory?.name].filter(Boolean).join(' › ');
}
